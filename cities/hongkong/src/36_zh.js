/* Chinese text on any plane P(a, z) -> world point. The text starts at a0 (or is centred on it with o.center), each
   character an h x h square; horizontal (left to right along +a) or, with o.vert, a column down from ztop.
   ztop is the top of the first character. o.w: stroke width (wide px); o.glow: a translucent halo colour drawn first
   (neon). Unknown characters are skipped (never drawn as pseudo-strokes). */
HK.zh = function (g, P, a0, ztop, h, str, col, o) {
  o = o || {}; const s = Array.from(String(str)), gap = (o.gap == null ? 0.14 : o.gap) * h, n = s.length;
  const u = h / 20, segs = [];
  let a = o.vert ? a0 - h / 2 : (o.center ? a0 - (n * h + (n - 1) * gap) / 2 : a0), zt = ztop;
  for (const ch of s) {
    const gl = HK.ZH[ch];
    if (gl) for (const st of gl) for (let i = 0; i + 3 < st.length; i += 2) {
      const p0 = g.p.apply(g, P(a + st[i] * u, zt - st[i + 1] * u)), p1 = g.p.apply(g, P(a + st[i + 2] * u, zt - st[i + 3] * u));
      segs.push(p0[0], p0[1], p1[0], p1[1]);
    }
    if (o.vert) zt -= h + gap; else a += h + gap;
  }
  const w = o.w || clamp(h * 0.2, 0.18, 1.1);
  if (o.glow) g.segs2(segs, o.glow, w * 2.6);
  g.segs2(segs, col, w);
};
/* width (horizontal) or height (vertical) of a string of n characters at size h */
HK.zhW = (str, h, gap) => { const n = Array.from(String(str)).length; return n * h + (n - 1) * (gap == null ? 0.14 : gap) * h; };
/* on a building face, in K.on's coordinates: face 'L' (plane y = p, reads along +x), 'R' (plane x = p, reads along -y) */
HK.zhOn = function (g, face, p, a, ztop, h, str, col, o) {
  const P = face === 'L' ? (s, z) => [s, p + 0.07, z] : (s, z) => [p + 0.07, -s, z];
  HK.zh(g, P, face === 'L' ? a : -a, ztop, h, str, col, o);
};
